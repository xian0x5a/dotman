from __future__ import annotations

import difflib
import os
import stat
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Mapping

from dotman.atomic_files import write_text_atomic
from dotman.editor import editor_command
from dotman.errors import UsageError
from dotman.models import AdditionalSource
from dotman.command_runtime import CommandRequest, CommandResult, current_command_runtime
from dotman.file_access import chmod, read_bytes, write_bytes_atomic as sudo_write_bytes_atomic


_EXECUTABLE_BITS = stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH


@dataclass(frozen=True)
class EditableSourceCopy:
    destination_path: Path
    editable_copy_path: Path
    original_bytes: bytes = b""
    original_mode: int | None = None


def _read_diff_text(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8", errors="replace").splitlines()


def _dedupe_paths(paths: list[Path]) -> list[Path]:
    ordered_paths: list[Path] = []
    for path in paths:
        if path not in ordered_paths:
            ordered_paths.append(path)
    return ordered_paths


def _build_review_content(
    *,
    repo_path: Path,
    live_path: Path,
    editable_sources: list[EditableSourceCopy],
) -> str:
    diff_lines = list(
        difflib.unified_diff(
            _read_diff_text(repo_path),
            _read_diff_text(live_path),
            fromfile=str(repo_path),
            tofile=str(live_path),
            lineterm="",
        )
    )
    if not diff_lines:
        diff_body = "No differences detected.\n"
    else:
        diff_body = "\n".join(diff_lines) + "\n"
    editable_sources_text = "\n".join(
        (
            f"- repo destination: {editable_source.destination_path}\n"
            f"  editable copy: {editable_source.editable_copy_path}"
        )
        for editable_source in editable_sources
    )
    return (
        "# Dotman Editor Review\n\n"
        "Review only. Do not edit this file.\n"
        "Inspect the diff below, then edit the temporary source copies listed under editable sources.\n"
        "Saved edits return to the Deck as a new Proposal; nothing reaches the repo until it is approved and applied.\n"
        "\n"
        "## Review Inputs\n\n"
        f"- review repo path: {repo_path}\n"
        f"- review live path: {live_path}\n\n"
        "## Editable Sources\n\n"
        f"{editable_sources_text}\n\n"
        "## Diff\n\n"
        "```diff\n"
        f"{diff_body}"
        "```\n"
    )


def _write_read_only(path: Path, content: bytes) -> Path:
    path.write_bytes(content)
    path.chmod(0o444)
    return path


def _write_review_file(
    *,
    root: Path,
    repo_path: Path,
    live_path: Path,
    editable_sources: list[EditableSourceCopy],
) -> Path:
    content = _build_review_content(repo_path=repo_path, live_path=live_path, editable_sources=editable_sources)
    return _write_read_only(root / "review.md", content.encode("utf-8"))


def _write_editable_source_copies(
    *, root: Path, source_paths: list[Path], preserve_primary_executable: bool,
) -> list[EditableSourceCopy]:
    editable_sources: list[EditableSourceCopy] = []
    for index, source_path in enumerate(source_paths, start=1):
        editable_copy_path = root / f"editable-{index}-{source_path.name}"
        original_bytes = read_bytes(source_path)
        editable_copy_path.write_bytes(original_bytes)
        original_mode = stat.S_IMODE(source_path.stat().st_mode) if preserve_primary_executable and index == 1 else None
        if original_mode is not None:
            editable_copy_path.chmod(original_mode)
        editable_sources.append(
            EditableSourceCopy(
                destination_path=source_path,
                editable_copy_path=editable_copy_path,
                original_bytes=original_bytes,
                original_mode=original_mode,
            )
        )
    return editable_sources


def _changed_editable_sources(editable_sources: list[EditableSourceCopy]) -> list[EditableSourceCopy]:
    return [
        editable_source
        for editable_source in editable_sources
        if editable_source.editable_copy_path.read_bytes() != editable_source.original_bytes
        or editable_source.original_mode is not None and bool(editable_source.original_mode & _EXECUTABLE_BITS)
        != bool(editable_source.editable_copy_path.stat().st_mode & _EXECUTABLE_BITS)
    ]


def _write_changed_sources(changed_sources: list[EditableSourceCopy]) -> None:
    for changed_source in changed_sources:
        content = changed_source.editable_copy_path.read_bytes()
        try:
            write_text_atomic(
                changed_source.destination_path,
                content.decode("utf-8"),
            )
        except (PermissionError, UnicodeDecodeError):
            # Source inputs may be readable only through the elevation broker,
            # and binary editor inputs must still be copied byte-for-byte.
            sudo_write_bytes_atomic(changed_source.destination_path, content)
        if changed_source.original_mode is not None:
            # Only child Git executable state is editable; exact permissions are live policy.
            executable = bool(changed_source.editable_copy_path.stat().st_mode & _EXECUTABLE_BITS)
            chmod(changed_source.destination_path, (changed_source.original_mode & ~_EXECUTABLE_BITS)
                  | (_EXECUTABLE_BITS if executable else 0))


def resolve_editor_additional_sources(entries: tuple[AdditionalSource, ...]) -> list[Path]:
    # Resolve each configured entry against the package that declared it.
    # Entries from inherited specs retain their parent root; appended entries
    # carry the child root.
    source_paths: list[Path] = []
    for entry in entries:
        root = entry.root.expanduser().resolve()
        source_path = (root / entry.path).resolve()
        try:
            source_path.relative_to(root)
        except ValueError as exc:
            raise UsageError(f"editor additional source escapes declaring package root: {entry.path}") from exc
        source_paths.append(source_path)
    return source_paths


def run_basic_reconcile(
    *,
    repo_path: Path,
    additional_sources: list[Path],
    review_repo_bytes: bytes,
    review_live_bytes: bytes,
    editor: str | None,
    editor_env: Mapping[str, str],
    editor_cwd: Path,
    editor_io: str,
    editor_elevation: str,
    preserve_primary_executable: bool,
) -> CommandResult:
    """Edit transactional copies of the sources beside a read-only review, then write changed copies back.

    The Sync Editor stages `repo_path` and `additional_sources` in a private
    workspace, so writing back never touches the repository itself.
    """
    source_paths = _dedupe_paths([repo_path, *additional_sources])
    with tempfile.TemporaryDirectory(prefix="dotman-editor-") as temp_dir:
        temp_root = Path(temp_dir)
        editable_sources = _write_editable_source_copies(
            root=temp_root, source_paths=source_paths, preserve_primary_executable=preserve_primary_executable,
        )
        review_repo_path = _write_read_only(temp_root / "review-repo", review_repo_bytes)
        review_live_path = _write_read_only(temp_root / "review-live", review_live_bytes)
        review_file_path = _write_review_file(
            root=temp_root, repo_path=review_repo_path, live_path=review_live_path, editable_sources=editable_sources,
        )
        primary_copy = str(editable_sources[0].editable_copy_path)
        command_env = {
            **editor_env,
            "DOTMAN_EDITOR_REVIEW_PATH": str(review_file_path),
            "DOTMAN_EDITOR_SOURCE_PATH": primary_copy,
            "DOTMAN_EDITOR_PRIMARY_PATH": primary_copy,
            "DOTMAN_EDITOR_TRANSACTIONAL_ROOT": str(temp_root),
            "DOTMAN_EDITOR_ADDITIONAL_SOURCE_PATHS": os.pathsep.join(
                str(source.editable_copy_path) for source in editable_sources[1:]
            ),
            # Existing command helpers use these names; point them at the
            # staged, readable inputs so an editor cannot mutate managed files.
            "DOTMAN_REVIEW_REPO_PATH": str(review_repo_path),
            "DOTMAN_REVIEW_LIVE_PATH": str(review_live_path),
            "DOTMAN_REPO_PATH": primary_copy,
            "DOTMAN_SOURCE": primary_copy,
            "DOTMAN_LIVE_PATH": str(review_live_path),
        }
        # Editors receive only editable sources positionally. The review is
        # intentionally discoverable through DOTMAN_EDITOR_REVIEW_PATH so a
        # provider cannot accidentally treat the read-only review as writable.
        command = editor_command([str(source.editable_copy_path) for source in editable_sources], explicit=editor)
        if command is None:
            raise ValueError("could not resolve an editor")
        result = current_command_runtime().run(
            CommandRequest(command=command, env=command_env, cwd=editor_cwd, io=editor_io, elevation=editor_elevation)
        )
        if result.exit_code == 0:
            _write_changed_sources(_changed_editable_sources(editable_sources))
        return result
